  for (var r = 0; r < ROWS; r++) {
    for (var c = 0; c < COLS; c++) ORDER.push('d' + r + c);
  }

  function artToSpec(rows) {
    var on = [];
    for (var r = 0; r < ROWS; r++) {
      var line = rows[r] || '';
      for (var c = 0; c < COLS; c++) {
        if (line.charAt(c) === '#') on.push('d' + r + c);
      }
    }
    return on.join(' ');
  }

  var FONT = {};
  Object.keys(ART).forEach(function (ch) {
    var rows = ART[ch];
    if (rows.length !== ROWS) throw new Error('5x7 font: ' + ch + ' has ' + rows.length + ' rows');
    rows.forEach(function (line) {
      if (line.length !== COLS) throw new Error('5x7 font: ' + ch + ' row "' + line + '" is not ' + COLS + ' wide');
    });
    FONT[ch] = [artToSpec(rows)];
  });

  NS.matrix = { COLS: COLS, ROWS: ROWS, ART: ART, FONT: FONT, ORDER: ORDER };
