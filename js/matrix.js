/* matrix.js — 5x7 dot-matrix font and grid geometry.
 *
 * A different animal from the segment displays: no fixed strokes, just a grid. This is
 * the thing segment displays were always losing to, and it is modelled on an outdoor
 * monochrome message sign — the kind where each PIXEL is a cluster of discrete
 * through-hole LEDs rather than one. The clusters exist for daylight: a single 5 mm die
 * at 20 mA cannot be read in direct sun, and seven per pixel multiply the output without
 * growing the pixel. Seven, not four: they sit in a centred hexagonal "flower", one in
 * the middle ringed by six, and a complete flower only exists at 1, 7, 19, 37, 61.
 *
 * The font is authored as ASCII art on purpose. Five hex bytes per glyph is the compact
 * firmware format, and it is unreviewable — you cannot see a mistake in 0x7E 0x11 0x11.
 * Here you can read the letter in the source, which is how errors get caught.
 *
 * SIBLING COPY: `~/code/barcom-web`, `resources/js/matrix.js`, which renders Don's
 * Rednex readerboards. The ART table is vendored between the two by hand — two repos,
 * no build relationship, and a font is a static asset rather than a dependency. The
 * two tables are currently identical; if you edit one, diff the other.
 */
